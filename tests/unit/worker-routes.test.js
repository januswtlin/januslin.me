// run_worker_first from topics and pages (T10, #59): src/lib/content/worker-routes.ts and the
// scripts/sync-worker-routes.ts command, on a temporary wrangler.jsonc (the real one is T14's).
import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { afterAll, describe, expect, it } from "vitest";
import { scanContent } from "../../src/lib/content/scan.ts";
import { replaceWorkerRoutes, workerRoutes } from "../../src/lib/content/worker-routes.ts";

const root = resolve(import.meta.dirname, "../..");
const FIXTURE_ROUTES = [
  "/coffee/*",
  "/travel/*",
  "/tech/*",
  "/en/coffee/*",
  "/en/travel/*",
  "/en/tech/*",
  "/about/",
  "/en/about/",
];

const tmp = mkdtempSync(join(tmpdir(), "worker-routes-"));
afterAll(() => rmSync(tmp, { recursive: true, force: true }));

const JSONC = `{
  "name": "januslin-me",
  "assets": {
    // Generated by scripts/sync-worker-routes.ts.
    "run_worker_first": ["/old/*"],
    "binding": "ASSETS"
  }
}
`;

/** @param {string[]} args @param {Record<string, string>} [env] */
const run = (args, env = {}) =>
  spawnSync("node", ["scripts/sync-worker-routes.ts", ...args], {
    cwd: root,
    encoding: "utf8",
    env: { ...process.env, CONTENT_DIR: "tests/fixtures/content", ...env },
  });

describe("workerRoutes", () => {
  it("lists topic hubs (by order, then id) in both locales, then pages where they exist", () => {
    expect(workerRoutes(scanContent(root, "tests/fixtures/content"))).toEqual(FIXTURE_ROUTES);
  });

  it("leaves out English pages that are effectively drafts, the same as the collections", () => {
    const page = (/** @type {string} */ locale, /** @type {Record<string, unknown>} */ data) => ({
      collection: /** @type {const} */ ("pages"),
      slug: "about",
      locale,
      file: `content/pages/about/index.${locale}.md`,
      data: { title: "t", description: "d", ...data },
      body: "",
    });
    const scan = (/** @type {any[]} */ entries) => ({
      root,
      contentDir: "content",
      files: [],
      entries,
      tags: { file: "", exists: true, items: [] },
    });
    // zh-TW published, English draft: only the zh-TW page.
    expect(workerRoutes(scan([page("zh-tw", {}), page("en", { draft: true })]))).toEqual([
      "/about/",
    ]);
    // zh-TW published, English published: both.
    expect(workerRoutes(scan([page("zh-tw", {}), page("en", {})]))).toEqual([
      "/about/",
      "/en/about/",
    ]);
    // zh-TW draft: neither, whatever the English file says.
    expect(
      workerRoutes(scan([page("zh-tw", { draft: true }), page("en", { draft: false })])),
    ).toEqual([]);
  });

  it("is empty for the empty content/ skeleton", () => {
    expect(workerRoutes(scanContent(root, "content"))).toEqual([]);
  });

  it("replaces only the run_worker_first array, keeping comments", () => {
    const out = replaceWorkerRoutes(JSONC, ["/a/*", "/en/a/*"]);
    expect(out).toContain('"run_worker_first": ["/a/*", "/en/a/*"],');
    expect(out).toContain("// Generated by scripts/sync-worker-routes.ts.");
    expect(out.replace(/"run_worker_first": \[[^\]]*\]/, "")).toBe(
      JSONC.replace(/"run_worker_first": \[[^\]]*\]/, ""),
    );
    expect(() => replaceWorkerRoutes("{}", [])).toThrow(/run_worker_first/);
  });
});

describe("pnpm sync-worker-routes", () => {
  it("--check passes with a notice while wrangler.jsonc does not exist", () => {
    const r = run(["--check", "--config", join(tmp, "missing.jsonc")]);
    expect(r.status).toBe(0);
    expect(r.stdout).toMatch(/does not exist yet/);
  });

  it("--check fails on a stale file and names the command; the default mode updates it", () => {
    const file = join(tmp, "wrangler.jsonc");
    writeFileSync(file, JSONC);
    const stale = run(["--check", "--config", file]);
    expect(stale.status).toBe(1);
    expect(stale.stderr).toMatch(/out of date; run `pnpm sync-worker-routes`/);
    expect(readFileSync(file, "utf8")).toBe(JSONC);

    expect(run(["--config", file]).status).toBe(0);
    expect(readFileSync(file, "utf8")).toContain(
      `"run_worker_first": [${FIXTURE_ROUTES.map((r) => JSON.stringify(r)).join(", ")}]`,
    );
    const fresh = run(["--check", "--config", file]);
    expect(fresh.status).toBe(0);
    expect(fresh.stdout).toMatch(/up to date \(8 patterns\)/);
  });

  it("rejects unknown options", () => {
    expect(run(["--force"]).status).toBe(2);
  });
});
